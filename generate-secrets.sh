#!/bin/sh
# Generates the secrets of this stack: .env (passwords, tokens, keys) and the
# files in secrets/ (Docker secrets for mihon-source and source-mihon).
#
# It never overwrites: an existing .env or secret file is kept, so running it
# again only fills in what is missing. To start over, delete .env and
# secrets/*.txt first, and the volumes too (the database keeps the old
# passwords): docker compose down -v.
set -eu
cd "$(dirname "$0")"
umask 077

if ! command -v openssl >/dev/null 2>&1; then
	echo "openssl is needed to generate random secrets" >&2
	exit 1
fi
hex() { openssl rand -hex "${1:-24}"; }
b64() { openssl rand -base64 32; }

created=""
if [ -e .env ]; then
	echo ".env exists; keeping it"
else
	cat > .env <<EOF
# Generated by generate-secrets.sh on $(date -u +%Y-%m-%d). Keep it private and
# back it up with the volumes: the secret keys decrypt what the services store.
# Settings you may change are in .env.example.

# PostgreSQL: the superuser, and one role per service.
POSTGRES_PASSWORD=$(hex)
META_DB_PASSWORD=$(hex)
PANELARR_DB_PASSWORD=$(hex)

# meta: its admin token (sign in to http://localhost:8901 with it), the key
# that encrypts its stored secrets, and the key meta uses with its plugin.
META_ADMIN_TOKEN=mta_$(hex 32)
META_SECRET_KEY=$(b64)
MANGABAKA_PLUGIN_KEY=$(hex 32)

# The Panelarr server: the key that encrypts its stored secrets.
PANELARR_SECRET_KEY=$(b64)

# Optional search engines (profiles search-typesense, search-meilisearch).
TYPESENSE_API_KEY=$(hex 32)
MEILI_MASTER_KEY=$(hex 32)
EOF
	created="$created .env"
fi

# The directory stays private; the files are world-readable so the services'
# non-root users can read them where Docker bind-mounts them.
mkdir -p secrets
chmod 700 secrets
secret() { # name, value
	if [ -e "secrets/$1.txt" ]; then
		echo "secrets/$1.txt exists; keeping it"
	else
		printf '%s\n' "$2" > "secrets/$1.txt"
		chmod 644 "secrets/$1.txt"
		created="$created secrets/$1.txt"
	fi
}
# mihon-source's admin token (sign in to http://localhost:8902 with it), and
# the key that encrypts its stored proxy passwords.
secret mihon_admin_token "$(hex 32)"
secret mihon_secret_key "$(b64)"
# The key the Panelarr server sends to source-mihon (enter it when adding the
# plugin in Panelarr).
secret source_mihon_api_key "$(hex 32)"
# A client key you create in mihon-source's admin: replaced in step 4.
secret mihon_source_api_key "replace-with-a-mihon-source-client-key"

if [ -n "$created" ]; then
	echo "created:$created"
fi
echo "next: see README.md, 'First run'"
